from google.colab import userdata
from google import genai

api_key = userdata.get("GEMINI_API_KEY")

client = genai.Client(api_key=api_key)

# Gemini model
MODEL = "gemini-3.6-flash"

print("Gemini API connection initialized successfully!")

def send_prompt(prompt):
    response = client.models.generate_content(
        model=MODEL,
        contents=prompt
    )
    return response.text

baseline_prompt = "What is recursion?"

enhanced_prompt = (
    "You are a computer science professor. "
    "Explain recursion to a beginner using a simple real-world analogy. "
    "Give a clear definition and one example. "
    "Keep the explanation under 50 words."
)

baseline_response = send_prompt(baseline_prompt)

enhanced_response = send_prompt(enhanced_prompt)

print("\n" + "=" * 70)
print("        EXPERIMENT 2: PROMPT ENGINEERING")
print("=" * 70)


print("\n=== BASELINE PROMPT ===")
print("Prompt:")
print(baseline_prompt)

print("\nResponse:")
print(baseline_response)


print("\n" + "-" * 70)


print("\n=== ENHANCED PROMPT ===")
print("Prompt:")
print(enhanced_prompt)

print("\nResponse:")
print(enhanced_response)

print("\n" + "=" * 70)
print("                    ANALYSIS")
print("=" * 70)

print("""
The baseline prompt provides only a general instruction,
so the response may be less structured.

The enhanced prompt provides a specific role, context,
real-world analogy, example requirement, and word limit.

Therefore, the enhanced prompt produces a more focused,
clear, and beginner-friendly response.
""")

print("=" * 70)
